(function () {
  'use strict';

  function detectLang() {
    try {
      var urlLang = new URLSearchParams(location.search).get('lang');
      if (urlLang === 'hu' || urlLang === 'en') {
        try { localStorage.setItem('imperius-lang', urlLang); } catch (e) {}
        return urlLang;
      }
      var saved = localStorage.getItem('imperius-lang');
      if (saved === 'hu' || saved === 'en') return saved;
    } catch (e) {}
    // Defaults to Hungarian for everyone (primary audience); visitors
    // can switch to English with the nav toggle.
    return 'hu';
  }

  function applyLanguage(lang) {
    var dict = window.IMPERIUS_I18N[lang] || window.IMPERIUS_I18N.hu;
    document.documentElement.setAttribute('lang', dict.html_lang);
    document.documentElement.setAttribute('data-lang', lang);

    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      var key = el.getAttribute('data-i18n');
      if (dict[key] !== undefined) el.textContent = dict[key];
    });
    document.querySelectorAll('[data-i18n-attr]').forEach(function (el) {
      var spec = el.getAttribute('data-i18n-attr').split(':');
      var attr = spec[0], key = spec[1];
      if (dict[key] !== undefined) el.setAttribute(attr, dict[key]);
    });
    // Templated strings, e.g. data-i18n-template="footer_credit" with
    // data-slot-year filling the "{year}" placeholder (kept fresh here).
    document.querySelectorAll('[data-slot-year]').forEach(function (el) {
      el.setAttribute('data-slot-year', new Date().getFullYear());
    });
    document.querySelectorAll('[data-i18n-template]').forEach(function (el) {
      var key = el.getAttribute('data-i18n-template');
      var tpl = dict[key];
      if (tpl === undefined) return;
      el.textContent = tpl.replace(/\{(\w+)\}/g, function (_, name) {
        return el.getAttribute('data-slot-' + name) || '';
      });
    });

    var pageKey = document.body.getAttribute('data-page');
    if (pageKey) {
      var titleKey = 'meta_title_' + pageKey;
      var descKey = 'meta_desc_' + pageKey;
      if (dict[titleKey]) document.title = dict[titleKey];
      if (dict[descKey]) {
        var m = document.querySelector('meta[name="description"]');
        if (m) m.setAttribute('content', dict[descKey]);
      }
    }

    try { localStorage.setItem('imperius-lang', lang); } catch (e) {}
    document.dispatchEvent(new CustomEvent('imperius:langchange', { detail: { lang: lang } }));
  }

  window.ImperiusI18N = { apply: applyLanguage, detect: detectLang, get: function (lang) { return window.IMPERIUS_I18N[lang] || window.IMPERIUS_I18N.hu; } };

  document.addEventListener('DOMContentLoaded', function () {
    applyLanguage(detectLang());
  });
})();
